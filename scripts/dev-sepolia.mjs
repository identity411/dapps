#!/usr/bin/env node
/**
 * Start the Sepolia demo stack: Relay + Web.
 *
 * Usage:
 *   npm start
 *   npm run dev:sepolia
 *
 * Reads SEPOLIA_RPC_URL and the Relay secrets from the repository-root .env,
 * validates deployments/sepolia.json against the live RPC, generates the
 * gitignored web/.env.sepolia, then launches both processes.
 */

import { spawn } from "node:child_process";
import fs from "node:fs";
import net from "node:net";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ENV_FILE = path.join(ROOT, ".env");
const DEPLOYMENT_FILE = path.join(ROOT, "deployments", "sepolia.json");
const WEB_ENV_FILE = path.join(ROOT, "web", ".env.sepolia");
const WEB_PORT = 5173;
const RELAY_PORT = 8787;
const SEPOLIA_CHAIN_ID = 11155111;
const SEPOLIA_DB_PATH = path.join(ROOT, "relay", "data", "skinpact-sepolia.db");

const children = [];
let shuttingDown = false;

function fail(message) {
  console.error(`\n[sepolia] ${message}\n`);
  process.exit(1);
}

function loadEnvironment() {
  if (!fs.existsSync(ENV_FILE)) {
    fail("Repository-root .env not found. Copy .env.example to .env and fill it first.");
  }
  try {
    process.loadEnvFile(ENV_FILE);
  } catch (error) {
    fail(`Could not load .env: ${error instanceof Error ? error.message : String(error)}`);
  }
  for (const key of ["SEPOLIA_RPC_URL", "JWT_SECRET", "RELAY_ENCRYPTION_KEY"]) {
    if (!(process.env[key] || "").trim()) {
      fail(`${key} is missing from the repository-root .env.`);
    }
  }
}

function readDeployment() {
  if (!fs.existsSync(DEPLOYMENT_FILE)) {
    fail("deployments/sepolia.json not found. Deploy and record the Sepolia contract first.");
  }
  let deployment;
  try {
    deployment = JSON.parse(fs.readFileSync(DEPLOYMENT_FILE, "utf8"));
  } catch (error) {
    fail(`Could not parse deployments/sepolia.json: ${error instanceof Error ? error.message : String(error)}`);
  }
  if (deployment.chainId !== SEPOLIA_CHAIN_ID) {
    fail(`deployments/sepolia.json chainId must be ${SEPOLIA_CHAIN_ID}, got ${deployment.chainId}.`);
  }
  if (!/^0x[0-9a-fA-F]{40}$/.test(deployment.address || "")) {
    fail("deployments/sepolia.json does not contain a valid contract address.");
  }
  return deployment;
}

async function rpc(rpcUrl, method, params = []) {
  const response = await fetch(rpcUrl, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ jsonrpc: "2.0", method, params, id: 1 }),
    signal: AbortSignal.timeout(15_000),
  });
  if (!response.ok) throw new Error(`HTTP ${response.status}`);
  const body = await response.json();
  if (body.error) throw new Error(body.error.message || "JSON-RPC error");
  return body.result;
}

async function validateSepoliaDeployment(deployment) {
  const rpcUrl = process.env.SEPOLIA_RPC_URL.trim();
  try {
    const rawChainId = await rpc(rpcUrl, "eth_chainId");
    const chainId = Number.parseInt(rawChainId, 16);
    if (chainId !== SEPOLIA_CHAIN_ID) {
      fail(`SEPOLIA_RPC_URL points to chain ${chainId}, expected ${SEPOLIA_CHAIN_ID}.`);
    }
    const code = await rpc(rpcUrl, "eth_getCode", [deployment.address, "latest"]);
    if (!code || code === "0x") {
      fail(`No contract code at ${deployment.address} on Sepolia. Check deployments/sepolia.json.`);
    }
  } catch (error) {
    fail(
      `Could not validate SEPOLIA_RPC_URL: ${
        error instanceof Error ? error.message : String(error)
      }`,
    );
  }
}

function writeWebEnvironment(deployment) {
  const content = [
    "# Generated by `npm start` / `npm run dev:sepolia`. Do not edit or commit.",
    `VITE_CHAIN_ID=${SEPOLIA_CHAIN_ID}`,
    `VITE_RPC_URL=${process.env.SEPOLIA_RPC_URL.trim()}`,
    `VITE_CONTRACT_ADDRESS=${deployment.address}`,
    `VITE_RELAY_URL=http://127.0.0.1:${RELAY_PORT}`,
    "VITE_HELPER_URL=http://127.0.0.1:8788",
    "",
  ].join("\n");
  fs.writeFileSync(WEB_ENV_FILE, content, { mode: 0o600 });
  fs.chmodSync(WEB_ENV_FILE, 0o600);
  console.log("[sepolia] regenerated web/.env.sepolia (gitignored)");
}

function isListening(port, host) {
  return new Promise((resolve) => {
    const socket = net.connect({ port, host });
    const finish = (result) => {
      socket.destroy();
      resolve(result);
    };
    socket.setTimeout(400);
    socket.once("connect", () => finish(true));
    socket.once("timeout", () => finish(false));
    socket.once("error", () => finish(false));
  });
}

async function assertPortsFree() {
  const conflicts = [];
  if ((await isListening(WEB_PORT, "127.0.0.1")) || (await isListening(WEB_PORT, "::1"))) {
    conflicts.push(WEB_PORT);
  }
  if (await isListening(RELAY_PORT, "127.0.0.1")) {
    conflicts.push(RELAY_PORT);
  }
  if (conflicts.length > 0) {
    const detail = conflicts
      .map((port) => `  lsof -tiTCP:${port} -sTCP:LISTEN | xargs kill`)
      .join("\n");
    fail(
      `Port ${conflicts.join(" and ")} already in use. Stop the existing service(s):\n${detail}`,
    );
  }
}

function terminate(child, signal) {
  if (!child.pid) return;
  try {
    if (process.platform === "win32") child.kill(signal);
    else process.kill(-child.pid, signal);
  } catch {
    try {
      child.kill(signal);
    } catch {
      // Already gone.
    }
  }
}

function shutdown(exitCode) {
  if (shuttingDown) return;
  shuttingDown = true;
  console.log("\n[sepolia] Stopping Web and Relay…");
  for (const { child } of children) terminate(child, "SIGTERM");
  setTimeout(() => {
    for (const { child } of children) {
      if (child.exitCode === null && child.signalCode === null) terminate(child, "SIGKILL");
    }
    process.exit(exitCode);
  }, 1_000);
}

function startService(name, args, extraEnv) {
  const command = process.platform === "win32" ? "npm.cmd" : "npm";
  const child = spawn(command, args, {
    cwd: ROOT,
    env: { ...process.env, ...extraEnv },
    stdio: "inherit",
    detached: process.platform !== "win32",
  });
  children.push({ name, child });
  child.on("error", (error) => {
    console.error(`[sepolia] Failed to start ${name}: ${error.message}`);
    shutdown(1);
  });
  child.on("exit", (code, signal) => {
    if (shuttingDown) return;
    console.error(
      `[sepolia] ${name} stopped unexpectedly (${signal ? `signal ${signal}` : `exit ${code}`}).`,
    );
    shutdown(code ?? 1);
  });
  return child;
}

async function main() {
  loadEnvironment();
  const deployment = readDeployment();
  await validateSepoliaDeployment(deployment);
  writeWebEnvironment(deployment);
  await assertPortsFree();
  fs.mkdirSync(path.dirname(SEPOLIA_DB_PATH), { recursive: true });

  console.log("[sepolia] Starting the Sepolia demo stack");
  console.log(`[sepolia]   Web      http://localhost:${WEB_PORT}`);
  console.log(`[sepolia]   Relay    http://127.0.0.1:${RELAY_PORT}`);
  console.log(`[sepolia]   Chain    ${SEPOLIA_CHAIN_ID}`);
  console.log(`[sepolia]   Contract ${deployment.address}`);
  console.log("[sepolia] MetaMask must be on Sepolia. Press Ctrl-C to stop both services.\n");

  startService("relay", ["run", "relay"], {
    CHAIN_ID: String(SEPOLIA_CHAIN_ID),
    RPC_URL: process.env.SEPOLIA_RPC_URL.trim(),
    CONTRACT_ADDRESS: deployment.address,
    DEPLOYMENT_BLOCK: String(deployment.deploymentBlock || 0),
    DB_PATH: SEPOLIA_DB_PATH,
    PORT: String(RELAY_PORT),
    WEB_ORIGIN: `http://localhost:${WEB_PORT}`,
  });
  startService("web", ["run", "web:sepolia"]);

  process.on("SIGINT", () => shutdown(0));
  process.on("SIGTERM", () => shutdown(0));
}

main().catch((error) => {
  console.error(`[sepolia] Startup failed: ${error instanceof Error ? error.message : String(error)}`);
  shutdown(1);
});
